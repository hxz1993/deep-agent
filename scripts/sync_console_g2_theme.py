#!/usr/bin/env python3
"""Build the Console theme from the bundled spreadsheet Skill, without npm.

Run after replacing the built-in Agent package; --check verifies committed output.
The Skill's data/financial rules are deliberately not chart-wide defaults.
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
from pathlib import Path
import re
import zipfile

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "src/deep_agent/agent_packages/builtin/deeptable-assistant.zip"
OUTPUT = ROOT / "console/g2-theme.js"


def render_theme(package: Path = PACKAGE) -> str:
    with zipfile.ZipFile(package) as agent:
        with zipfile.ZipFile(io.BytesIO(agent.read("skills/deepfos-financial-charts.zip"))) as skill:
            raw = skill.read("assets/theme.json")
            tokens = json.loads(raw)
            frontmatter = skill.read("SKILL.md").decode("utf-8").split("---", 2)[1]
    if tokens["g2Version"] != "5.4.8":
        raise ValueError("Bundled Skill G2 version differs from the pinned Console renderer")
    version = re.search(r"^\s+version:\s*[\"']?([\w.-]+)", frontmatter, re.M)
    if version is None:
        raise ValueError("Bundled chart Skill version is missing")
    metadata = {
        "skillVersion": version[1],
        "sourceSha256": hashlib.sha256(raw).hexdigest(),
        "tokens": tokens,
    }
    payload = json.dumps(metadata, ensure_ascii=False, indent=2).replace("</", "<\\/")
    return '''// Generated by scripts/sync_console_g2_theme.py; edit the bundled chart Skill instead.
(function registerDeepAgentG2Theme(global) {
  "use strict";
  const source = ''' + payload + ''';
  const { colors: c, sizes: s, fontFamily, categoryColors } = source.tokens;
  const name = "deepfos";
  const defaults = {
    color: c.actual, category10: categoryColors, category20: categoryColors,
    view: { viewFill: c.background },
    line: { line: { lineWidth: s.line } },
    axis: {
      labelFill: c.mutedText, labelOpacity: 1, labelFontFamily: fontFamily, labelFontSize: s.category,
      titleFill: c.text, titleOpacity: 1, titleFontFamily: fontFamily, titleFontSize: s.label,
      gridStroke: c.border, gridStrokeOpacity: 1, lineStroke: c.border, tickStroke: c.border,
    },
    title: {
      titleFill: c.text, titleFontSize: s.title, titleFontFamily: fontFamily,
      subtitleFill: c.mutedText, subtitleFontSize: s.caption, subtitleFontFamily: fontFamily,
    },
    legendCategory: {
      itemLabelFill: c.text, itemLabelFontSize: s.category, itemLabelFontFamily: fontFamily,
      itemValueFill: c.mutedText, itemValueFontSize: s.label, itemValueFontFamily: fontFamily,
      titleFill: c.text, titleFontSize: s.label, titleFontFamily: fontFamily,
    },
    legendContinuous: {
      labelFill: c.mutedText, labelFontSize: s.label, labelFontFamily: fontFamily,
      titleFill: c.text, titleFontSize: s.label, titleFontFamily: fontFamily,
    },
    label: { fill: c.text, fillOpacity: 1, fontSize: s.label, fontFamily, connectorStroke: c.border },
    innerLabel: { fill: c.inverseText, fontSize: s.label, fontFamily },
    text: { text: { fill: c.text, fontSize: s.label, fontFamily } },
  };
  // G2 passes theme-object fields to the registered factory. Merge them last,
  // recursively, so a single explicit font/color never erases sibling defaults.
  function merge(base, override) {
    const result = { ...base };
    for (const [key, value] of Object.entries(override || {})) {
      if (["__proto__", "constructor", "prototype"].includes(key)) continue;
      if (value && typeof value === "object" && !Array.isArray(value)) result[key] = merge(base?.[key], value);
      else if (value !== undefined) result[key] = Array.isArray(value) ? [...value] : value;
    }
    return result;
  }
  function create(overrides = {}) { return global.G2.Light(merge(defaults, overrides)); }
  create.props = {};
  global.G2.register(`theme.${name}`, create);
  global.DeepAgentG2Theme = Object.freeze({ name, ...source, create });
})(window);
'''


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render_theme()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text("utf-8") != expected:
            print("Console G2 theme is stale; run scripts/sync_console_g2_theme.py")
            return 1
        print("Console G2 theme matches the bundled Skill")
    else:
        OUTPUT.write_text(expected, encoding="utf-8")
        print(f"Updated {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
